function parseBirthPlace(value) {
  const parts = String(value || "")
    .split(/\s+/)
    .map((part) => part.trim())
    .filter(Boolean);
  return {
    province: parts[0] || "",
    city: parts[1] || "",
    district: parts[2] || ""
  };
}

function formatBirthPlace(selection) {
  return [selection.province, selection.city, selection.district].filter(Boolean).join(" ");
}

