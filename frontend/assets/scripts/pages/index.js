function parseBold(text) {
  const segments = [];
  const matcher = /\*\*(.+?)\*\*/g;
  let cursor = 0;
  let result;
  while ((result = matcher.exec(text)) !== null) {
    if (result.index > cursor) {
      segments.push({ text: text.slice(cursor, result.index), bold: false });
    }
    segments.push({ text: result[1], bold: true });
    cursor = result.index + result[0].length;
  }
  if (cursor < text.length) {
    segments.push({ text: text.slice(cursor), bold: false });
  }
  return segments;
}

function wrapText(ctx, text, x, y, maxWidth, lineHeight) {
  const characters = Array.from(text);
  let line = "";
  const lines = [];
  characters.forEach((character) => {
    const candidate = line + character;
    if (ctx.measureText(candidate).width > maxWidth && line) {
      lines.push(line);
      line = character;
    } else {
      line = candidate;
    }
  });
  if (line) lines.push(line);
  lines.forEach((content, index) => ctx.fillText(content, x, y + index * lineHeight));
  return lines.length;
}

function drawRichText(ctx, segments, x, y, maxWidth, options) {
  const {
    fontSize = 14,
    lineHeight = 28,
    fontFamily = '"PingFang SC", sans-serif',
    normalColor = "#3d2a35",
    boldColor = "#ff8b7a"
  } = options;
  let cursorX = x;
  let cursorY = y;
  let lineCount = 1;

  segments.forEach((segment) => {
    ctx.font = `${segment.bold ? "700" : "400"} ${fontSize}px ${fontFamily}`;
    ctx.fillStyle = segment.bold ? boldColor : normalColor;

    Array.from(segment.text).forEach((character) => {
      if (character === "\n") {
        cursorX = x;
        cursorY += lineHeight;
        lineCount += 1;
        return;
      }
      const width = ctx.measureText(character).width;
      if (cursorX + width > x + maxWidth) {
        cursorX = x;
        cursorY += lineHeight;
        lineCount += 1;
      }
      ctx.fillText(character, cursorX, cursorY);
      cursorX += width;
    });
  });

  return { endY: cursorY, lines: lineCount };
}

function createTextGradient(ctx, x, y, width, height, colors) {
  const gradient = ctx.createLinearGradient(x, y, x + width, y + height);
  colors.forEach((color, index) => gradient.addColorStop(index / (colors.length - 1), color));
  return gradient;
}

function roundRect(ctx, x, y, width, height, radius) {
  ctx.beginPath();
  ctx.moveTo(x + radius, y);
  ctx.lineTo(x + width - radius, y);
  ctx.quadraticCurveTo(x + width, y, x + width, y + radius);
  ctx.lineTo(x + width, y + height - radius);
  ctx.quadraticCurveTo(x + width, y + height, x + width - radius, y + height);
  ctx.lineTo(x + radius, y + height);
  ctx.quadraticCurveTo(x, y + height, x, y + height - radius);
  ctx.lineTo(x, y + radius);
  ctx.quadraticCurveTo(x, y, x + radius, y);
  ctx.closePath();
}

function drawHeart(ctx, centerX, centerY, size, fillStyle) {
  ctx.save();
  ctx.translate(centerX, centerY);
  const scale = size / 100;
  ctx.scale(scale, scale);
  ctx.beginPath();
  ctx.moveTo(0, 30);
  ctx.bezierCurveTo(-60, -10, -50, -50, -25, -50);
  ctx.bezierCurveTo(-10, -50, 0, -35, 0, -20);
  ctx.bezierCurveTo(0, -35, 10, -50, 25, -50);
  ctx.bezierCurveTo(50, -50, 60, -10, 0, 30);
  ctx.closePath();
  ctx.fillStyle = fillStyle;
  ctx.fill();
  ctx.restore();
}

function fitFontSize(ctx, text, maxWidth, baseSize, minSize, weight, family) {
  let size = baseSize;
  while (size > minSize) {
    ctx.font = `${weight} ${size}px ${family}`;
    if (ctx.measureText(text).width <= maxWidth) break;
    size -= 2;
  }
  return size;
}

