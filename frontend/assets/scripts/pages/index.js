function initSlideGestures() {
  const slides = $("form-slides");
  if (!slides) return;

  slides.addEventListener("pointerdown", (event) => {
    if (isInteractiveTarget(event.target)) return;
    dragState = {
      startX: event.clientX,
      startY: event.clientY,
      index: THEME_ORDER.indexOf(currentTheme),
      width: getSliderWidth(),
      direction: null,
      moved: false,
      pointerId: event.pointerId
    };
    slides.classList.add("dragging");
  });

  slides.addEventListener("pointermove", (event) => {
    if (!dragState) return;
    const deltaX = event.clientX - dragState.startX;
    const deltaY = event.clientY - dragState.startY;
    if (!dragState.direction) {
      if (Math.abs(deltaX) < 8 && Math.abs(deltaY) < 8) return;
      dragState.direction = Math.abs(deltaX) > Math.abs(deltaY) ? "x" : "y";
    }
    if (dragState.direction !== "x") return;

    dragState.moved = true;
    event.preventDefault();
    const resistance =
      (dragState.index === 0 && deltaX > 0) || (dragState.index === THEME_ORDER.length - 1 && deltaX < 0)
        ? 0.35
        : 1;
    updateSlidePosition(false, deltaX * resistance);
  });

  const endDrag = (event) => {
    if (!dragState) return;
    const activeDrag = dragState;
    dragState = null;
    slides.classList.remove("dragging");

    if (activeDrag.direction !== "x" || !activeDrag.moved) {
      updateSlidePosition(true);
      return;
    }

    const deltaX = event.clientX - activeDrag.startX;
    const threshold = Math.min(120, activeDrag.width * 0.18);
    let nextIndex = activeDrag.index;

    if (deltaX <= -threshold && activeDrag.index < THEME_ORDER.length - 1) {
      nextIndex += 1;
    } else if (deltaX >= threshold && activeDrag.index > 0) {
      nextIndex -= 1;
    }

    setTheme(THEME_ORDER[nextIndex]);
    hideFormError();
  };

  slides.addEventListener("pointerup", endDrag);
  slides.addEventListener("pointercancel", () => {
    if (!dragState) return;
    dragState = null;
    slides.classList.remove("dragging");
    updateSlidePosition(true);
  });

  window.addEventListener("resize", () => { updateSlidePosition(true); updateTabIndicator(); });
}

