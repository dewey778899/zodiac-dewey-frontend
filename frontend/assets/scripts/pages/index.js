function updateSlidePosition(animate = true, extraOffset = 0) {
  const slides = $("form-slides");
  const shell = $("form-slider-shell");
  if (!slides) return;
  if (animate) {
    slides.classList.remove("dragging");
  } else {
    slides.classList.add("dragging");
  }
  const index = THEME_ORDER.indexOf(currentTheme);
  const width = getSliderWidth();
  slides.style.transform = `translateX(${-(index * width) + extraOffset}px)`;
  // 动态设置容器高度为当前 slide 的高度，避免空白
  const currentSlide = slides.querySelectorAll(".form-slide")[index];
  if (currentSlide && shell) {
    const targetH = currentSlide.getBoundingClientRect().height;
    if (animate) {
      shell.style.transition = "height 0.32s ease";
    } else {
      shell.style.transition = "none";
    }
    shell.style.height = targetH + "px";
  }
}

