/** 将爱情模块 person-a 的资料同步到单人模块（事业/财运） */
function syncPersonAFromLoveToSingle() {
  const loveSlide = document.querySelector('.form-slide[data-theme="love"]');
  const currentSlide = document.querySelector(`.form-slide[data-theme="${currentTheme}"]`);
  if (!loveSlide || !currentSlide) return;

  // 同步名字
  const loveName = loveSlide.querySelector('[data-person="a"][data-field="name"]');
  const singleName = currentSlide.querySelector('[data-person="a"][data-field="name"]');
  if (loveName && singleName && loveName.value) {
    singleName.value = loveName.value;
  }

  // 同步性别
  const loveGenderBtns = loveSlide.querySelectorAll('[data-person="a"].gender-btn');
  const singleGenderBtns = currentSlide.querySelectorAll('[data-person="a"].gender-btn');
  loveGenderBtns.forEach((btn) => {
    if (btn.classList.contains("active")) {
      singleGenderBtns.forEach((singleBtn) => {
        singleBtn.classList.toggle("active", singleBtn.dataset.value === btn.dataset.value);
      });
    }
  });

  // 同步年月日
  const loveYear = loveSlide.querySelector('[data-person="a"][data-field="birthYear"]');
  const loveMonth = loveSlide.querySelector('[data-person="a"][data-field="birthMonth"]');
  const loveDay = loveSlide.querySelector('[data-person="a"][data-field="birthDay"]');
  const singleYear = currentSlide.querySelector('[data-person="a"][data-field="birthYear"]');
  const singleMonth = currentSlide.querySelector('[data-person="a"][data-field="birthMonth"]');
  const singleDay = currentSlide.querySelector('[data-person="a"][data-field="birthDay"]');
  if (loveYear && singleYear && loveYear.value) singleYear.value = loveYear.value;
  if (loveMonth && singleMonth && loveMonth.value) singleMonth.value = loveMonth.value;
  if (loveDay && singleDay && loveDay.value) singleDay.value = loveDay.value;

  // 同步时间
  const loveTime = loveSlide.querySelector('[data-person="a"][data-field="birthTime"]');
  const singleTime = currentSlide.querySelector('[data-person="a"][data-field="birthTime"]');
  if (loveTime && singleTime && loveTime.value) singleTime.value = loveTime.value;

  // 同步城市
  const loveCityText = loveSlide.querySelector('[data-person="a"] .city-picker-text');
  const singleCityText = currentSlide.querySelector('[data-person="a"] .city-picker-text');
  if (loveCityText && singleCityText && loveCityText.textContent && loveCityText.textContent !== "点击选择省 / 市 / 区") {
    singleCityText.textContent = loveCityText.textContent;
  }
}

