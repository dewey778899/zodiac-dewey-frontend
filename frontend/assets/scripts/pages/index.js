function renderLoadingSteps() {
  const container = $("loading-steps");
  if (!container) return;
  const theme = getThemeConfig(currentTheme);
  container.innerHTML = theme.loadingSteps
    .map(
      (step, index) => `
        <div class="loading-step pending" data-step="${index}">
          <div class="loading-step-status">${String(index + 1).padStart(2, "0")}</div>
          <div class="loading-step-copy">
            <div class="loading-step-title">${step.title}</div>
            <div class="loading-step-sub">${step.desc}</div>
          </div>
        </div>
      `
    )
    .join("");
}

function getLoadingStepIndex(progress) {
  for (let index = 0; index < LOADING_PROGRESS_TARGETS.length; index += 1) {
    if (progress < LOADING_PROGRESS_TARGETS[index]) return index;
  }
  return LOADING_PROGRESS_TARGETS.length - 1;
}

function updateLoadingUI(stepIndex, progress) {
  const percent = Math.max(0, Math.min(100, Math.round(progress)));
  const theme = getThemeConfig(currentTheme);
  const steps = theme.loadingSteps;
  const fill = $("loading-progress-fill");
  const label = $("loading-progress-label");
  const value = $("loading-progress-value");

  if (fill) fill.style.width = `${percent}%`;
  if (value) value.textContent = `${percent}%`;

  if (label) {
    if (stepIndex < 0) {
      label.textContent = "准备开始...";
    } else if (stepIndex >= steps.length) {
      label.textContent = "全部完成，马上展示报告";
    } else {
      label.textContent = `正在：${steps[stepIndex].title}`;
    }
  }

  document.querySelectorAll(".loading-step").forEach((node, index) => {
    node.classList.remove("pending", "active", "completed");
    const status = node.querySelector(".loading-step-status");
    if (stepIndex >= steps.length || index < stepIndex) {
      node.classList.add("completed");
      if (status) status.textContent = "✓";
      return;
    }
    if (index === stepIndex) {
      node.classList.add("active");
      if (status) status.textContent = "···";
      return;
    }
    node.classList.add("pending");
    if (status) status.textContent = String(index + 1).padStart(2, "0");
  });
}

function startLoadingProgress() {
  stopLoadingProgress();
  renderLoadingSteps();
  loadingProgress = 8;
  updateLoadingUI(0, loadingProgress);
  loadingTimer = window.setInterval(() => {
    const increment = loadingProgress < 38 ? 5 : loadingProgress < 68 ? 4 : loadingProgress < 88 ? 3 : 1;
    loadingProgress = Math.min(94, loadingProgress + increment);
    updateLoadingUI(getLoadingStepIndex(loadingProgress), loadingProgress);
  }, 900);
}

function stopLoadingProgress() {
  if (loadingTimer) {
    clearInterval(loadingTimer);
    loadingTimer = null;
  }
}

function completeLoadingProgress() {
  stopLoadingProgress();
  loadingProgress = 100;
  updateLoadingUI(getThemeConfig(currentTheme).loadingSteps.length, loadingProgress);
}

function resetLoadingProgress() {
  stopLoadingProgress();
  loadingProgress = 0;
  renderLoadingSteps();
  updateLoadingUI(-1, 0);
}

