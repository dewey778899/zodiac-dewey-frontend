function cacheReport(report, form) {
  if (!report?.reportUid) return;
  const cache = readReportCache();
  cache[report.reportUid] = {
    report,
    form,
    cachedAt: Date.now()
  };
  const entries = Object.entries(cache)
    .sort(([, left], [, right]) => (right.cachedAt || 0) - (left.cachedAt || 0))
    .slice(0, REPORT_CACHE_LIMIT);
  writeReportCache(Object.fromEntries(entries));
}

